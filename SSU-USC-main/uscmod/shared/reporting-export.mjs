import {
  attendanceStatistics,
  complaintMetrics,
  complaintBreakdown,
} from "./reporting-model.mjs";
const safe = (value) => String(value ?? "").slice(0, 32000);
const excelDate = (ms) => (ms > 0 ? new Date(ms + 8 * 3600000) : null);
export const MAX_EXCEL_ROWS = 10000;
export function buildReportingWorkbook(
  ExcelJS,
  {
    type,
    rows,
    context,
    actor,
    atMs,
    complete = true,
    closed = false,
    details = true,
    activitySummary = null,
    eventSummaries = [],
    completionTrend = [],
  },
) {
  if (rows.length > MAX_EXCEL_ROWS)
    throw Error(
      "Excel reports are limited to 10,000 records. Narrow your filters.",
    );
  const book = new ExcelJS.Workbook();
  book.creator = "SSU University Student Council";
  book.created = new Date(atMs);
  book.modified = new Date(atMs);
  const title =
    type === "attendance"
      ? "Attendance"
      : type === "complaints"
        ? "Complaints and Feedback"
        : "Student Council Activities";
  function sheet(name, headers, widths) {
    const ws = book.addWorksheet(name);
    ws.columns = headers.map((header, i) => ({
      header,
      width: widths?.[i] || 24,
    }));
    ws.spliceRows(
      1,
      0,
      ["SAMAR STATE UNIVERSITY — UNIVERSITY STUDENT COUNCIL"],
      [`${title} Report`],
      [safe(context)],
      [
        `Generated by: ${safe(actor)} | ${new Date(atMs).toLocaleString("en-PH", { timeZone: "Asia/Manila" })} (Asia/Manila)`,
      ],
      [],
    );
    for (let i = 1; i <= 4; i++) {
      ws.mergeCells(i, 1, i, headers.length);
      ws.getRow(i).font = {
        bold: i < 3,
        size: i === 1 ? 14 : 11,
        color: { argb: "FF264D32" },
      };
    }
    ws.views = [{ state: "frozen", ySplit: 6 }];
    ws.autoFilter = {
      from: { row: 6, column: 1 },
      to: { row: Math.max(6, rows.length + 6), column: headers.length },
    };
    return ws;
  }
  function style(ws) {
    for (let n = 6; n <= ws.rowCount; n++) {
      const row = ws.getRow(n);
      row.height = n === 6 ? 32 : 25;
      row.eachCell({ includeEmpty: true }, (cell) => {
        cell.font = {
          name: "Calibri",
          size: 11,
          bold: n === 6,
          color: { argb: n === 6 ? "FFFFFFFF" : "FF243C30" },
        };
        cell.fill = {
          type: "pattern",
          pattern: "solid",
          fgColor: {
            argb: n === 6 ? "FF365E3B" : n % 2 ? "FFF0F5ED" : "FFFFFFFF",
          },
        };
        cell.border = {
          bottom: { style: "thin", color: { argb: "FFDEE7DC" } },
        };
        cell.alignment = { vertical: "middle", wrapText: n === 6 };
      });
    }
    ws.autoFilter.to = { row: ws.rowCount, column: ws.columnCount };
  }
  const summary = sheet(
    type === "attendance" ? "Attendance Summary" : "Report Summary",
    ["Metric", "Value"],
    [52, 60],
  );
  if (type === "attendance") {
    const stats = attendanceStatistics(rows, { complete, closed });
    for (const [label, key] of [
      ["Eligible student-event opportunities", "eligible"],
      ["Registered student-event records", "registered"],
      ["Actual student-event attendances", "attended"],
      ["Unique actual attendees", "uniqueAttendees"],
      ["Completed", "completed"],
      ["Incomplete", "incomplete"],
      ["Absent", "absent"],
    ])
      summary.addRow([label, stats[key] ?? "N/A"]);
    for (const [label, key] of [
      ["Participation rate", "participationRate"],
      ["Registration rate", "registrationRate"],
      ["Registered student attendance rate", "attendanceRate"],
      ["Attendance completion rate", "completionRate"],
      ["Absence rate (finalized)", "absenceRate"],
      ["Incomplete rate (finalized)", "incompleteRate"],
    ]) {
      const row = summary.addRow([
        label,
        stats[key] == null ? "N/A" : stats[key] / 100,
      ]);
      row.getCell(2).numFmt = "0.00%";
    }
    summary.addRow([
      "Historical eligibility",
      complete
        ? "Captured at publication"
        : "Unavailable — registered records only; eligibility-based rates N/A",
    ]);
    const breakdown = sheet("Academic Breakdown", [
      "Department",
      "Program",
      "Year",
      "Section",
      "Eligible",
      "Registered",
      "Attended",
      "Completed",
      "Incomplete",
      "Absent",
      "Participation rate",
    ]);
    const groups = new Map();
    for (const row of rows) {
      const key = JSON.stringify([
        row.college,
        row.program,
        row.yearLevel,
        row.section,
      ]);
      if (!groups.has(key)) groups.set(key, []);
      groups.get(key).push(row);
    }
    for (const [key, group] of [...groups].sort(([a], [b]) =>
      a.localeCompare(b),
    )) {
      const s = attendanceStatistics(group, { complete, closed }),
        r = breakdown.addRow([
          ...JSON.parse(key).map(safe),
          s.eligible ?? "N/A",
          s.registered,
          s.attended,
          s.completed,
          s.incomplete,
          s.absent,
          s.participationRate == null ? "N/A" : s.participationRate / 100,
        ]);
      r.getCell(11).numFmt = "0.00%";
    }
    if (details) {
      const ws = sheet(
        "Individual Attendance Records",
        [
          "No.",
          "Student ID",
          "Full Name",
          "Department",
          "Program",
          "Year Level",
          "Section",
          "Event / Program",
          "Registration Date and Time",
          "Time-in",
          "Time-out",
          "Attendance Duration",
          "Participation Status",
          "Time-in Officer UID",
          "Time-out Officer UID",
        ],
        [8, 22, 32, 35, 38, 18, 18, 36, 26, 26, 26, 22, 22, 32, 32],
      );
      const sorted = [...rows].sort(
        (a, b) =>
          ["college", "program", "yearLevel", "section", "fullName"]
            .map((k) => safe(a[k]).localeCompare(safe(b[k])))
            .find((n) => n) || 0,
      );
      sorted.forEach((r, i) => {
        const line = ws.addRow([
          i + 1,
          safe(r.studentId),
          safe(r.fullName),
          safe(r.college),
          safe(r.program),
          safe(r.yearLevel),
          safe(r.section),
          safe(r.eventTitle),
          excelDate(r.registeredAtMs),
          excelDate(r.timeInAtMs),
          excelDate(r.timeOutAtMs),
          r.durationMs == null ? null : r.durationMs / 86400000,
          safe(r.status),
          safe(r.timeInOfficerUid),
          safe(r.timeOutOfficerUid),
        ]);
        line.getCell(2).numFmt = "@";
        for (const c of [9, 10, 11])
          line.getCell(c).numFmt = "mmm d, yyyy h:mm AM/PM";
        line.getCell(12).numFmt = "[h]:mm";
      });
      ws.addConditionalFormatting({
        ref: `M7:M${Math.max(7, ws.rowCount)}`,
        rules: [
          "Completed",
          "Incomplete",
          "Absent",
          "Checked In",
          "Registered",
          "Not Registered",
        ].map((status, i) => ({
          type: "containsText",
          operator: "containsText",
          text: status,
          priority: i + 1,
          style: {
            font: {
              bold: true,
              color: {
                argb: [
                  "FF246335",
                  "FF9A6700",
                  "FFAE2838",
                  "FF256695",
                  "FF526955",
                  "FF697279",
                ][i],
              },
            },
          },
        })),
      });
    }
  } else if (type === "complaints") {
    const s = complaintMetrics(rows, atMs);
    for (const [k, v] of Object.entries(s.counts)) summary.addRow([k, v]);
    summary.addRow(["Total", s.total]);
    summary.addRow(["Verified resolved", s.resolved]);
    const rate = summary.addRow([
      "Verified resolution rate",
      s.resolutionRate == null ? "N/A" : s.resolutionRate / 100,
    ]);
    rate.getCell(2).numFmt = "0.00%";
    summary.addRow([
      "Average resolution time (hours)",
      s.averageResolutionMs == null ? "N/A" : s.averageResolutionMs / 3600000,
    ]);
    summary.addRow(["Valid resolution timestamp samples", s.resolutionSamples]);
    summary.addRow([
      "Confidentiality",
      "Complainant identity, descriptions and attachments excluded",
    ]);
    const ws = sheet("Department Breakdown", [
      "Department",
      "Complaints",
      "Share",
    ]);
    for (const r of complaintBreakdown(rows, "college")) {
      const x = ws.addRow([safe(r.label), r.count, r.percentage / 100]);
      x.getCell(3).numFmt = "0.00%";
    }
    if (details) {
      const cases = sheet("Complaint Records", [
        "Reference ID",
        "Subject",
        "Department",
        "Submitted",
        "Assigned officer UID",
        "Status",
        "Updated",
        "Resolved",
        "Category",
      ]);
      for (const r of rows) {
        const line = cases.addRow([
          safe(r.reference),
          safe(r.subject),
          safe(r.college),
          excelDate(r.createdAtMs),
          safe(r.assignedOfficer),
          safe(r.status),
          excelDate(r.updatedAtMs),
          excelDate(r.resolvedAtMs),
          safe(r.category),
        ]);
        for (const c of [4, 7, 8])
          line.getCell(c).numFmt = "mmm d, yyyy h:mm AM/PM";
      }
    }
  } else {
    summary.addRow(["Recorded activities", rows.length]);
    summary.addRow([
      "Historical limitations",
      "Only available authorized audit metadata is included",
    ]);
    if (activitySummary) {
      for (const [label, value] of [
        ["Conducted events/programs", activitySummary.conducted],
        ["Upcoming events/programs", activitySummary.upcoming],
        ["Ongoing events/programs", activitySummary.ongoing],
        [
          "Actual student-event attendances",
          activitySummary.participation.attended,
        ],
        [
          "Verified resolved complaints",
          activitySummary.complaints?.resolved ?? "Not authorized",
        ],
        [
          "Complaints received",
          activitySummary.complaints?.total ?? "Not authorized",
        ],
      ])
        summary.addRow([label, value]);
      const events = sheet("Events and Participation", [
        "Event / program",
        "Date",
        "Academic year",
        "Semester",
        "Evidence",
        "Eligible",
        "Registered",
        "Attended",
        "Completed",
        "Participation rate",
        "Completion rate",
      ]);
      for (const e of eventSummaries) {
        const s = e.metrics,
          r = events.addRow([
            safe(e.title),
            excelDate(
              Date.parse(
                (e.eventDate || e.archivedEventDate) + "T00:00:00+08:00",
              ),
            ),
            safe(e.academicYear),
            safe(e.semester),
            safe(e.evidence),
            s.eligible ?? "N/A",
            s.registered,
            s.attended,
            s.completed,
            s.participationRate == null ? "N/A" : s.participationRate / 100,
            s.completionRate == null ? "N/A" : s.completionRate / 100,
          ]);
        r.getCell(2).numFmt = "mmm d, yyyy";
        for (const c of [10, 11]) r.getCell(c).numFmt = "0.00%";
      }
      const trend = sheet("Completion Trend", [
        "Time-in month",
        "Completion rate",
      ]);
      for (const entry of completionTrend) {
        const r = trend.addRow([entry.label, entry.count / 100]);
        r.getCell(2).numFmt = "0.00%";
      }
    }
    const ws = sheet("Activity Records", [
      "Date and Time",
      "Officer",
      "Officer UID",
      "Module",
      "Action",
      "Record title",
      "Status",
      "Administration",
    ]);
    for (const r of rows) {
      const line = ws.addRow([
        excelDate(r.createdAtMs),
        safe(r.officerName),
        safe(r.officerUid),
        safe(r.module),
        safe(r.action),
        safe(r.recordTitle),
        safe(r.status),
        safe(r.administration),
      ]);
      line.getCell(1).numFmt = "mmm d, yyyy h:mm AM/PM";
    }
  }
  for (const ws of book.worksheets) style(ws);
  return book;
}
export function reportFilename(type, context) {
  return `USC_${type}_${
    String(context)
      .replace(/[^a-zA-Z0-9_-]/g, "_")
      .slice(0, 120) || "Overall"
  }.xlsx`;
}
